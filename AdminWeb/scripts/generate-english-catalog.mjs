import fs from "node:fs";

const inputPath = new URL("../.tmp/i18n-values.txt", import.meta.url);
const outputPath = new URL("../src/i18n.generated.ts", import.meta.url);
const values = [
  ...new Set(
    fs
      .readFileSync(inputPath, "utf8")
      .replace(/^\uFEFF/, "")
      .split(/\r?\n/)
      .map((value) => value.trim())
      .filter(Boolean)
  )
];

const translated = new Map();
let nextIndex = 0;
await Promise.all(Array.from({length: 8}, () => worker()));

async function worker() {
  while (nextIndex < values.length) {
    const index = nextIndex++;
    const value = values[index];
    translated.set(value, await translate(value));
  }
}

async function translate(value, attempt = 1) {
  const endpoint = new URL("https://translate.googleapis.com/translate_a/single");
  endpoint.searchParams.set("client", "gtx");
  endpoint.searchParams.set("sl", "zh-CN");
  endpoint.searchParams.set("tl", "en");
  endpoint.searchParams.set("dt", "t");
  endpoint.searchParams.set("q", value);

  const response = await fetch(endpoint);
  if (!response.ok) {
    if (attempt < 4 && (response.status === 429 || response.status >= 500)) {
      await new Promise((resolve) => setTimeout(resolve, attempt * 500));
      return translate(value, attempt + 1);
    }
    throw new Error(`Translation request failed with HTTP ${response.status} for ${value}`);
  }
  const payload = await response.json();
  return payload[0]
    .map((segment) => segment[0])
    .join("")
    .trim()
    .replace(/\s+/g, " ");
}

const lines = [
  "// Generated by scripts/generate-english-catalog.mjs; product terminology may be overridden in i18n.tsx.",
  "export const generatedEnglishCatalog: Record<string, string> = {",
  ...values.map((value) => `  ${JSON.stringify(value)}: ${JSON.stringify(translated.get(value))},`),
  "};",
  ""
];
fs.writeFileSync(outputPath, lines.join("\n"), "utf8");
